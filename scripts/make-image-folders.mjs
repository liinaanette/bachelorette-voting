/* Creates one folder per venue under /images, so photos are easy to file.
 *
 *   node scripts/make-image-folders.mjs
 *
 * Folder names are venue ids, which is what venues.js references. Rerun it
 * after adding a venue; it never touches a folder that already exists.
 */

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");

// venues.js is a browser file that assigns to window — give it one to assign to.
const window = {};
new Function("window", readFileSync(resolve(root, "venues.js"), "utf8"))(window);

const rows = [];
for (const venue of window.VENUES) {
  const dir = resolve(root, "images", venue.id);
  mkdirSync(dir, { recursive: true });
  const keep = resolve(dir, ".gitkeep");
  // git won't track an empty folder, so each one needs a file in it
  if (!existsSync(keep)) writeFileSync(keep, "");
  rows.push(`| \`${venue.id}/\` | ${venue.name} | ${venue.area} | [site](${venue.link}) |`);
}

writeFileSync(resolve(root, "images", "README.md"), `# Venue photos

One folder per venue. Drop 1–3 photos into the matching folder, then list them
on that venue in \`venues.js\`:

\`\`\`js
photos: ["images/barefoot/1.jpg", "images/barefoot/2.jpg"]
\`\`\`

Any venue left on \`photos: []\` keeps its generated placeholder, so you can do
these a few at a time. Aim for ~1200 px wide and under 200 KB each —
[squoosh.app](https://squoosh.app) compresses in the browser.

| Folder | Venue | Where | Site |
|---|---|---|---|
${rows.join("\n")}

*Folders and this index are generated by \`scripts/make-image-folders.mjs\`.*
`);

console.log(`${window.VENUES.length} venue folders ready under images/`);
